const ENQUEUE_AFTER: &str = r#"{"type":"queue-operation","operation":"enqueue","timestamp":"2026-11-13T13:20:00.000Z","content":"and then fix the build"}"#;
const ENQUEUE_NOTE: &str = r#"{"type":"queue-operation","operation":"enqueue","timestamp":"2026-11-13T13:20:10.000Z","content":"<task-notification><task-id>b1</task-id><status>completed</status></task-notification>"}"#;
