from __future__ import annotations

import unicodedata
import unittest

import check
import emit_rust
from tests.golden_util import assert_golden
from tests.helpers import TREE, small_tree


def render_files(files, ship=("en",), draft=()):
    work = small_tree(files, ship=ship, draft=draft)
    try:
        tree, loaded = check.load(work.locales)
        assert not loaded, [str(p) for p in loaded]
        return emit_rust.render(tree)
    finally:
        work.cleanup()


BASE = "language-name = English\n"


class EmitRustTests(unittest.TestCase):
    def test_golden(self):
        tree, problems = check.load(TREE)
        self.assertEqual(problems, [])
        assert_golden(self, "generated.rs", emit_rust.render(tree))

    def test_header_is_the_only_comment(self):
        tree, _ = check.load(TREE)
        text = emit_rust.render(tree)
        self.assertEqual(text.splitlines()[0], "// @generated by tools/locale/gen.py from locales/; do not edit.")
        self.assertEqual([l for l in text.splitlines() if l.lstrip().startswith("//")], [text.splitlines()[0]])

    def test_phone_messages_are_left_out(self):
        tree, _ = check.load(TREE)
        text = emit_rust.render(tree)
        self.assertNotIn("pub mod pairing", text)
        self.assertNotIn("pairing-title", text)

    def test_keyword_function_name(self):
        text = render_files({"en/shared.ftl": BASE, "en/mac/chat.ftl": "chat-move = Move\n"})
        self.assertIn("pub fn r#move() -> &'static str", text)
        self.assertIn("pub const MOVE: Text", text)

    def test_keyword_parameter_name(self):
        text = render_files({"en/shared.ftl": BASE, "en/mac/chat.ftl": "chat-x = A { $type }\n"})
        self.assertIn("pub fn x(r#type: &str) -> String", text)

    def test_hidden_character_is_escaped(self):
        text = render_files({"en/shared.ftl": BASE, "en/mac/chat.ftl": 'chat-joiner = a{"\\u200c"}b\n'})
        self.assertIn("\\u{200c}", text)
        self.assertEqual([c for c in text if unicodedata.category(c) == "Cf"], [])

    def test_braces_stay_plain(self):
        text = render_files({"en/shared.ftl": BASE, "en/mac/chat.ftl": 'chat-braces = Use {"{"}x{"}"}\n'})
        self.assertIn('Body::Plain("Use {x}")', text)

    def test_draft_language_not_built(self):
        text = render_files(
            {"en/shared.ftl": BASE, "de/shared.ftl": "language-name = Deutsch\n"}, draft=("de",)
        )
        self.assertNotIn('"de"', text)
        self.assertIn('("en", Table::Full(&EN))', text)

    def test_shipped_translation_has_a_partial_table(self):
        tree, _ = check.load(TREE)
        text = emit_rust.render(tree)
        self.assertIn("pub(crate) static PT_BR: [Option<Body>; COUNT]", text)
        self.assertIn('("pt-BR", Table::Part(&PT_BR))', text)
        self.assertNotIn("DE:", text)

    def test_ids_follow_sorted_keys(self):
        tree, _ = check.load(TREE)
        text = emit_rust.render(tree)
        self.assertIn('("chat-move", Text(0))', text)
        self.assertIn('("chat-moved-to", Text(1))', text)

    def test_plural_and_number_parts(self):
        tree, _ = check.load(TREE)
        text = emit_rust.render(tree)
        self.assertIn("Body::Plural(0, &[(Cat::One, &[Part::Int(0), Part::Lit(\" subagent running\")])", text)
        self.assertIn("Body::Parts(&[Part::Int(0), Part::Lit(\"m\")])", text)
        self.assertIn("Body::Parts(&[Part::Lit(\"Moved to \"), Part::Str(0)])", text)

    def test_brand_term_is_inlined(self):
        tree, _ = check.load(TREE)
        text = emit_rust.render(tree)
        self.assertIn('Body::Plain("Notchling isn\'t running")', text)


if __name__ == "__main__":
    unittest.main()
