const NOTIFICATION: &str = r#"{"type":"user","message":{"role":"user","content":"<task-notification><task-id>b1</task-id><status>completed</status></task-notification>"},"timestamp":"2026-11-13T13:15:52.300Z"}"#;
const INTERRUPT: &str = r#"{"type":"user","message":{"role":"user","content":[{"type":"text","text":"[Request interrupted by user]"}]},"timestamp":"2026-11-13T13:15:52.300Z"}"#;

fn fixture_lines() -> Vec<String> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/queue/lost-queue.jsonl");
    std::fs::read_to_string(path)
        .expect("fixture")
        .lines()
        .map(String::from)
        .collect()
}

fn read(lines: &[String]) -> Conversation {
    let scratch = Scratch::new("lost-queue");
    let path = scratch.write("q.jsonl", &(lines.join("\n") + "\n"));
    conversation::read(&s(&path))
}

fn read_str(lines: &[&str]) -> Conversation {
    read(&lines.iter().map(|l| (*l).to_string()).collect::<Vec<_>>())
}

fn phone(lines: &[String]) -> Vec<ChatMessage> {
    chat::parse(lines, true, "s-2", 50).messages
}

fn phone_str(lines: &[&str]) -> Vec<ChatMessage> {
    phone(&lines.iter().map(|l| (*l).to_string()).collect::<Vec<_>>())
}

fn queued_texts(messages: &[ChatMessage]) -> Vec<&str> {
    messages
        .iter()
        .filter(|m| m.queued)
        .map(|m| m.text.as_str())
        .collect()
}

fn users(c: &Conversation) -> Vec<String> {
    c.items
        .iter()
        .filter_map(|i| match &i.kind {
            ItemKind::User { text, .. } => Some(text.clone()),
            _ => None,
        })
        .collect()
}

#[test]
fn a_message_claude_code_lost_is_not_left_queued() {
    let c = read(&fixture_lines());
    assert_eq!(c.queued, Vec::<String>::new());
    assert_eq!(
        users(&c),
        [
            "Tidy the reply box",
            "[Image #20]why?",
            "when we switch accounts can you trust the folder for me",
            "yes",
        ]
    );
}

#[test]
fn the_phone_chat_view_drops_a_message_claude_code_lost() {
    let messages = phone(&fixture_lines());
    assert_eq!(queued_texts(&messages), Vec::<&str>::new(), "{messages:?}");
}

#[test]
fn the_lost_message_is_queued_until_a_prompt_arrives_without_a_dequeue() {
    let lines = &fixture_lines()[..3];
    assert_eq!(read(lines).queued, [LOST]);
    assert_eq!(queued_texts(&phone(lines)), [LOST]);
}

#[test]
fn a_message_queued_after_a_direct_prompt_stays_queued() {
    let mut lines = fixture_lines()[..5].to_vec();
    lines.push(ENQUEUE_AFTER.to_string());
    assert_eq!(read(&lines).queued, [AFTER]);
    assert_eq!(queued_texts(&phone(&lines)), [AFTER]);
}

#[test]
fn a_prompt_a_dequeue_explains_leaves_the_entries_behind_it_queued() {
    let lines = [ENQUEUE_LOST, ENQUEUE_AFTER, DEQUEUE, TAKES_LOST];
    assert_eq!(read_str(&lines).queued, [AFTER]);
    assert_eq!(queued_texts(&phone_str(&lines)), [AFTER]);
}

#[test]
fn every_entry_before_a_direct_prompt_is_dropped() {
    for prompt in [DIRECT, DIRECT_BLOCKS, DIRECT_BASH] {
        let lines = [ENQUEUE_LOST, ENQUEUE_AFTER, prompt];
        assert_eq!(read_str(&lines).queued, Vec::<String>::new(), "{prompt}");
        assert_eq!(
            queued_texts(&phone_str(&lines)),
            Vec::<&str>::new(),
            "{prompt}"
        );
    }
}

#[test]
fn a_line_that_is_not_a_typed_prompt_leaves_the_queue_alone() {
    for line in [
        TOOL_RESULT,
        CARRIED,
        META,
        SIDECHAIN,
        COMMAND,
        COMMAND_OUTPUT,
        NOTIFICATION,
        INTERRUPT,
    ] {
        let lines = [ENQUEUE_LOST, line];
        assert_eq!(read_str(&lines).queued, [LOST], "{line}");
        assert_eq!(queued_texts(&phone_str(&lines)), [LOST], "{line}");
    }
}

#[test]
fn a_notification_a_dequeue_explains_leaves_the_older_entry_for_the_next_direct_prompt() {
    let lines = [ENQUEUE_LOST, ENQUEUE_NOTE, DEQUEUE, NOTIFICATION];
    assert_eq!(read_str(&lines).queued, [LOST]);
    let lines = [ENQUEUE_LOST, ENQUEUE_NOTE, DEQUEUE, NOTIFICATION, DIRECT];
    assert_eq!(read_str(&lines).queued, Vec::<String>::new());
    assert_eq!(queued_texts(&phone_str(&lines)), Vec::<&str>::new());
}
