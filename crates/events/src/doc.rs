use crate::field::FieldDesc;
use crate::registry;
use crate::spec::{DefaultState, Durability, FieldSpec, Group, KindSpec, Lock};
use crate::value::write_str;

enum Json {
    Str(String),
    Bool(bool),
    Num(u64),
    Arr(Vec<Json>),
    Obj(Vec<(&'static str, Json)>),
}

fn strs<'a>(items: impl IntoIterator<Item = &'a str>) -> Json {
    Json::Arr(
        items
            .into_iter()
            .map(|s| Json::Str(s.to_string()))
            .collect(),
    )
}

fn write_compact(value: &Json, out: &mut String) {
    match value {
        Json::Str(s) => write_str(out, s),
        Json::Bool(b) => out.push_str(if *b { "true" } else { "false" }),
        Json::Num(n) => out.push_str(&n.to_string()),
        Json::Arr(items) => {
            out.push('[');
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_compact(item, out);
            }
            out.push(']');
        }
        Json::Obj(entries) => {
            out.push('{');
            for (i, (key, item)) in entries.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                write_str(out, key);
                out.push(':');
                write_compact(item, out);
            }
            out.push('}');
        }
    }
}

fn type_name(desc: &FieldDesc) -> String {
    match desc.ref_kind {
        Some(kind) => format!("ref:{kind}"),
        None => desc.ty.to_string(),
    }
}

fn field_json(f: &FieldSpec) -> Json {
    Json::Obj(vec![
        ("name", Json::Str(f.name.to_string())),
        ("type", Json::Str(type_name(&f.desc))),
        ("optional", Json::Bool(f.desc.optional)),
        ("list", Json::Bool(f.desc.list)),
        ("choices", strs(f.desc.choices.iter().copied())),
    ])
}

fn kind_head(spec: &KindSpec) -> Json {
    let lock = match spec.lock {
        Lock::Always(_) => "always",
        Lock::Toggle => "toggle",
    };
    Json::Obj(vec![
        ("name", Json::Str(spec.name.to_string())),
        ("kv", Json::Num(u64::from(spec.kv))),
        ("group", Json::Str(spec.group.name().to_string())),
        ("lock", Json::Str(lock.to_string())),
        ("sinks", strs(spec.sinks.names())),
        ("default", Json::Str(spec.default.name().to_string())),
        ("durability", Json::Str(spec.durability.name().to_string())),
        ("emitters", strs(spec.emitters.iter().map(|p| p.name()))),
        ("retired", Json::Bool(spec.retired)),
    ])
}

pub fn golden_json() -> String {
    let kinds = registry::all();
    let mut out = String::from("[\n");
    for (i, spec) in kinds.iter().enumerate() {
        let mut head = String::new();
        write_compact(&kind_head(spec), &mut head);
        head.pop();
        out.push_str("  ");
        out.push_str(&head);
        if spec.fields.is_empty() {
            out.push_str(",\"fields\":[]}");
        } else {
            out.push_str(",\"fields\":[\n");
            for (j, field) in spec.fields.iter().enumerate() {
                out.push_str("    ");
                write_compact(&field_json(field), &mut out);
                out.push_str(if j + 1 < spec.fields.len() {
                    ",\n"
                } else {
                    "\n"
                });
            }
            out.push_str("  ]}");
        }
        out.push_str(if i + 1 < kinds.len() { ",\n" } else { "\n" });
    }
    out.push_str("]\n");
    out
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

fn lock_cell(spec: &KindSpec) -> String {
    let mut text = match spec.lock {
        Lock::Always(reason) => format!("Always: {reason}"),
        Lock::Toggle => match spec.default {
            DefaultState::On => "Toggle, on.".to_string(),
            DefaultState::Off => "Toggle, off.".to_string(),
        },
    };
    if spec.durability == Durability::CommitFromAgent {
        text.push_str(" Commit before the effect.");
    }
    text
}

fn fields_cell(spec: &KindSpec) -> String {
    let parts: Vec<String> = spec
        .fields
        .iter()
        .map(|f| {
            let mark = if f.desc.list {
                "[]"
            } else if f.desc.optional {
                "?"
            } else {
                ""
            };
            let ty = type_name(&f.desc);
            if f.desc.ty == "choice" {
                format!("`{}{}` {} ({})", f.name, mark, ty, f.desc.choices.join("/"))
            } else {
                format!("`{}{}` {}", f.name, mark, ty)
            }
        })
        .collect();
    cell(&parts.join("; "))
}

pub fn markdown() -> String {
    let mut out = String::new();
    out.push_str("# Log kinds\n\n");
    out.push_str("Generated by `notchling log kinds --markdown`. Do not edit it by hand: change the registry in `crates/events/src/kinds/` and regenerate it.\n\n");
    out.push_str("A trailing `?` on a field means it is optional, `[]` that it is a list of at most 16. A choice lists its values; an unknown value is read as `other`. No field holds free text.\n");
    let all = registry::all();
    for group in Group::ALL {
        out.push_str(&format!("\n## {}\n\n", group.title()));
        out.push_str("| Kind | Title | Lock | Sinks | Records | Why | Fields |\n");
        out.push_str("| --- | --- | --- | --- | --- | --- | --- |\n");
        for spec in all.iter().filter(|s| s.group == group) {
            out.push_str(&format!(
                "| `{}` | {} | {} | {} | {} | {} | {} |\n",
                spec.name,
                cell(spec.title),
                cell(&lock_cell(spec)),
                spec.sinks.names().join(", "),
                cell(spec.records),
                cell(spec.why),
                fields_cell(spec),
            ));
        }
    }
    out
}
