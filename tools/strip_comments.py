#!/usr/bin/env python3
from __future__ import annotations

import argparse
import ast
import io
import json
import re
import subprocess
import sys
import tokenize
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

DESCRIPTION = (
    "Remove comments from Notchling's own source: Rust in crates/, Dart in apps/flutter/lib and test, "
    "Python in tools/, shell scripts in tools/ and the root. It scans with a tokenizer for each "
    "language, so strings, raw strings, char literals and URLs holding // are left alone. Run it with no "
    "arguments to rewrite the tree, --check to list what it would change, --count for the numbers."
)

SENTINEL = "\x00"

SCOPE = (
    ("rust", ("crates/",), (".rs",)),
    ("dart", ("apps/flutter/lib/", "apps/flutter/test/"), (".dart",)),
    ("python", ("tools/",), (".py",)),
    ("shell", ("tools/", ""), (".sh",)),
)

SKIP_NAMES = re.compile(r"(^|/)(generated\.rs|generated\.dart|app_localizations[^/]*\.dart)$")
SKIP_DIRS = ("vendor/", "legacy/", "crates/app/fixtures/", "/fixtures/", "/Fixtures/")
GENERATED_HEADER = re.compile(r"@generated|GENERATED CODE|DO NOT EDIT|Generated by", re.I)

KEEP_COMMON = re.compile(
    r"SPDX-License-Identifier|Copyright|@generated|DO NOT EDIT|CAP-OBSCURE|guard:\w"
)
KEEP_RUST = re.compile(r"^(rustfmt|clippy|cargo|miri|nocov|cov)[:\s]|^SAFETY\b")
KEEP_DART = re.compile(
    r"^(ignore:|ignore_for_file:|coverage:|dart format|@dart|ignore_for_file\b|ignore\b)"
)
KEEP_SHELL = re.compile(r"^(shellcheck|nolint|shfmt)\b")
KEEP_PYTHON = re.compile(
    r"^(noqa\b|type:|pragma\b|pylint:|pyright:|mypy:|fmt:|isort:|nosec\b|-\*-|flake8:|ruff:)"
)

OPENERS = "{([<"
CLOSERS = "})]>"


@dataclass
class Removed:
    path: str
    line: int
    kind: str
    text: str


@dataclass
class Result:
    text: str
    removed: List[Removed]
    kept: int


def split_lines(text: str, keepends: bool = True) -> List[str]:
    parts = text.split("\n")
    if keepends:
        out = [p + "\n" for p in parts[:-1]]
        if parts[-1]:
            out.append(parts[-1])
        return out
    if parts and parts[-1] == "":
        parts.pop()
    return parts


def is_ident(c: str) -> bool:
    return c.isalnum() or c == "_"


def rust_spans(text: str) -> List[Tuple[int, int, str]]:
    n = len(text)
    out: List[Tuple[int, int, str]] = []
    i = 0
    while i < n:
        c = text[i]
        if c == "/" and text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            if j > i and text[j - 1] == "\r":
                j -= 1
            doc = (text.startswith("///", i) and not text.startswith("////", i)) or text.startswith("//!", i)
            out.append((i, j, "doc" if doc else "line"))
            i = j
        elif c == "/" and text.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if text.startswith("/*", j):
                    depth += 1
                    j += 2
                elif text.startswith("*/", j):
                    depth -= 1
                    j += 2
                else:
                    j += 1
            doc = (text.startswith("/**", i) and not text.startswith("/***", i) and not text.startswith("/**/", i)) or text.startswith("/*!", i)
            out.append((i, j, "doc" if doc else "block"))
            i = j
        elif c == '"':
            i = rust_string(text, i + 1)
        elif c == "'":
            if text.startswith("\\", i + 1):
                j = i + 3
                while j < n and text[j] != "'":
                    j += 1
                i = j + 1
            elif text[i + 2:i + 3] == "'":
                i += 3
            else:
                i += 1
        elif is_ident(c):
            j = i
            while j < n and is_ident(text[j]):
                j += 1
            word = text[i:j]
            if word in ("r", "br", "cr") and j < n and text[j] in '#"':
                k = j
                while k < n and text[k] == "#":
                    k += 1
                if k < n and text[k] == '"':
                    close = '"' + "#" * (k - j)
                    e = text.find(close, k + 1)
                    i = n if e < 0 else e + len(close)
                    continue
            if word in ("b", "c") and j < n and text[j] == '"':
                i = rust_string(text, j + 1)
                continue
            if word == "b" and j < n and text[j] == "'":
                k = j + 1
                if text.startswith("\\", k):
                    k += 2
                else:
                    k += 1
                while k < n and text[k] != "'":
                    k += 1
                i = k + 1
                continue
            i = j
        else:
            i += 1
    return out


def rust_string(text: str, i: int) -> int:
    n = len(text)
    while i < n:
        c = text[i]
        if c == "\\":
            i += 2
        elif c == '"':
            return i + 1
        else:
            i += 1
    return n


def dart_spans(text: str) -> List[Tuple[int, int, str]]:
    out: List[Tuple[int, int, str]] = []
    scan_dart(text, 0, False, out)
    return out


def scan_dart(text: str, i: int, in_interp: bool, out: List[Tuple[int, int, str]]) -> int:
    n = len(text)
    depth = 0
    while i < n:
        c = text[i]
        if c == "/" and text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            if j > i and text[j - 1] == "\r":
                j -= 1
            out.append((i, j, "doc" if text.startswith("///", i) and not text.startswith("////", i) else "line"))
            i = j
        elif c == "/" and text.startswith("/*", i):
            level, j = 1, i + 2
            while j < n and level:
                if text.startswith("/*", j):
                    level += 1
                    j += 2
                elif text.startswith("*/", j):
                    level -= 1
                    j += 2
                else:
                    j += 1
            out.append((i, j, "doc" if text.startswith("/**", i) and not text.startswith("/**/", i) else "block"))
            i = j
        elif c in "'\"":
            i = dart_string(text, i, False, out)
        elif c == "r" and i + 1 < n and text[i + 1] in "'\"" and (i == 0 or not is_ident(text[i - 1])):
            i = dart_string(text, i + 1, True, out)
        elif in_interp and c == "{":
            depth += 1
            i += 1
        elif in_interp and c == "}":
            if depth == 0:
                return i + 1
            depth -= 1
            i += 1
        else:
            i += 1
    return n


def dart_string(text: str, i: int, raw: bool, out: List[Tuple[int, int, str]]) -> int:
    n = len(text)
    q = text[i]
    triple = text.startswith(q * 3, i)
    i += 3 if triple else 1
    closer = q * 3 if triple else q
    while i < n:
        c = text[i]
        if not raw and c == "\\":
            i += 2
        elif text.startswith(closer, i):
            return i + len(closer)
        elif c == "\n" and not triple:
            return i
        elif not raw and c == "$" and text.startswith("${", i):
            i = scan_dart(text, i + 2, True, out)
        else:
            i += 1
    return n


HEREDOC = re.compile(r"<<(-?)[ \t]*(?:'([^'\n]*)'|\"([^\"\n]*)\"|\\?([A-Za-z_][A-Za-z0-9_]*))")


def shell_spans(text: str) -> List[Tuple[int, int, str]]:
    n = len(text)
    out: List[Tuple[int, int, str]] = []
    pending: List[Tuple[str, bool]] = []
    i = 0
    while i < n:
        c = text[i]
        if c == "\n":
            i += 1
            while pending and i <= n:
                tag, strip = pending.pop(0)
                while i < n:
                    j = text.find("\n", i)
                    j = n if j < 0 else j
                    line = text[i:j]
                    i = min(j + 1, n)
                    if (line.lstrip("\t") if strip else line).rstrip("\r") == tag:
                        break
            continue
        if c == "\\":
            i += 2
            continue
        if c == "'":
            j = text.find("'", i + 1)
            i = n if j < 0 else j + 1
            continue
        if c == '"':
            i = shell_dquote(text, i + 1)
            continue
        if c == "`":
            j = i + 1
            while j < n and text[j] != "`":
                j += 2 if text[j] == "\\" else 1
            i = j + 1
            continue
        if c == "$":
            nxt = text[i + 1:i + 2]
            if nxt == "'":
                j = i + 2
                while j < n and text[j] != "'":
                    j += 2 if text[j] == "\\" else 1
                i = j + 1
                continue
            if nxt == "#":
                i += 2
                continue
            if nxt == "{":
                i = shell_braces(text, i + 2)
                continue
            if text.startswith("$((", i):
                i = shell_arith(text, i + 3)
                continue
            i += 1
            continue
        if c == "<" and text.startswith("<<", i) and not text.startswith("<<<", i):
            m = HEREDOC.match(text, i)
            if m:
                tag = m.group(2) if m.group(2) is not None else m.group(3) if m.group(3) is not None else m.group(4)
                pending.append((tag, m.group(1) == "-"))
                i = m.end()
                continue
        if c == "#" and (i == 0 or text[i - 1] in " \t\n;&|()\r"):
            j = text.find("\n", i)
            j = n if j < 0 else j
            if j > i and text[j - 1] == "\r":
                j -= 1
            out.append((i, j, "line"))
            i = j
            continue
        i += 1
    return out


def shell_dquote(text: str, i: int) -> int:
    n = len(text)
    while i < n:
        c = text[i]
        if c == "\\":
            i += 2
        elif c == '"':
            return i + 1
        elif c == "$" and text.startswith("$(", i) and not text.startswith("$((", i):
            i = shell_paren(text, i + 2)
        elif c == "$" and text.startswith("${", i):
            i = shell_braces(text, i + 2)
        elif c == "`":
            j = i + 1
            while j < n and text[j] != "`":
                j += 2 if text[j] == "\\" else 1
            i = j + 1
        else:
            i += 1
    return n


def shell_paren(text: str, i: int) -> int:
    n = len(text)
    depth = 1
    while i < n:
        c = text[i]
        if c == "\\":
            i += 2
        elif c == "'":
            j = text.find("'", i + 1)
            i = n if j < 0 else j + 1
        elif c == '"':
            i = shell_dquote(text, i + 1)
        elif c == "(":
            depth += 1
            i += 1
        elif c == ")":
            depth -= 1
            i += 1
            if depth == 0:
                return i
        else:
            i += 1
    return n


def shell_braces(text: str, i: int) -> int:
    n = len(text)
    depth = 1
    while i < n:
        c = text[i]
        if c == "\\":
            i += 2
        elif c == "'":
            j = text.find("'", i + 1)
            i = n if j < 0 else j + 1
        elif c == '"':
            i = shell_dquote(text, i + 1)
        elif c == "{":
            depth += 1
            i += 1
        elif c == "}":
            depth -= 1
            i += 1
            if depth == 0:
                return i
        else:
            i += 1
    return n


def shell_arith(text: str, i: int) -> int:
    n = len(text)
    depth = 2
    while i < n:
        c = text[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    return n


def comment_body(text: str, start: int, end: int, kind: str) -> str:
    raw = text[start:end]
    if raw.startswith("/*"):
        body = raw[2:-2] if raw.endswith("*/") else raw[2:]
        return body.lstrip("*!").strip()
    if raw.startswith("//"):
        return raw[2:].lstrip("/!").strip()
    return raw[1:].strip()


def keep_comment(lang: str, text: str, start: int, end: int, kind: str, line_no: int) -> bool:
    raw = text[start:end]
    body = comment_body(text, start, end, kind)
    if KEEP_COMMON.search(raw):
        return True
    if lang == "rust":
        return bool(KEEP_RUST.match(body)) and kind == "line"
    if lang == "dart":
        return bool(KEEP_DART.match(body)) and kind == "line"
    if lang == "shell":
        if line_no == 1 and raw.startswith("#!"):
            return True
        return bool(KEEP_SHELL.match(body))
    return False


def extend_safety(text: str, spans: List[Tuple[int, int, str]], keep: List[bool]) -> None:
    def line_start(p: int) -> int:
        return text.rfind("\n", 0, p) + 1

    for idx, (s, e, kind) in enumerate(spans):
        if not keep[idx] or kind != "line" or not re.match(r"//\s*SAFETY\b", text[s:e]):
            continue
        indent = s - line_start(s)
        if text[line_start(s):s].strip():
            continue
        j = idx + 1
        prev_end = e
        while j < len(spans):
            s2, e2, k2 = spans[j]
            if k2 != "line" or text[prev_end:s2].strip("\r\n ").strip() or text[prev_end:s2].count("\n") != 1:
                break
            if s2 - line_start(s2) != indent or text[line_start(s2):s2].strip():
                break
            keep[j] = True
            prev_end = e2
            j += 1


def python_spans(text: str, path: str) -> Tuple[List[Tuple[int, int, str]], List[Tuple[int, int, int, bool]]]:
    lines = split_lines(text)
    offsets = [0]
    for ln in lines:
        offsets.append(offsets[-1] + len(ln))
    spans: List[Tuple[int, int, str]] = []
    for tok in tokenize.generate_tokens(io.StringIO(text).readline):
        if tok.type == tokenize.COMMENT:
            (r1, c1), (r2, c2) = tok.start, tok.end
            spans.append((offsets[r1 - 1] + c1, offsets[r2 - 1] + c2, "line"))
    docstrings: List[Tuple[int, int, int, bool]] = []
    tree = ast.parse(text)
    uses_doc = "__doc__" in text

    def visit(body: List[ast.stmt], module: bool) -> None:
        for node in ast.walk(ast.Module(body=body, type_ignores=[])):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                first = node.body[0]
                if is_doc(first):
                    docstrings.append((first.lineno, first.end_lineno, first.col_offset, len(node.body) == 1))
        if body and is_doc(body[0]) and not (module and uses_doc):
            docstrings.append((body[0].lineno, body[0].end_lineno, body[0].col_offset, len(body) == 1))

    def is_doc(node: ast.stmt) -> bool:
        return isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str)

    visit(tree.body, True)
    seen = set()
    unique = []
    for d in docstrings:
        if d[:2] not in seen:
            seen.add(d[:2])
            unique.append(d)
    return spans, unique


def tidy(lines: List[Optional[str]], opener_ok: bool) -> str:
    out: List[str] = []
    gap = False
    for ln in lines:
        if ln is None:
            gap = True
            continue
        blank = not ln.strip()
        if gap:
            if blank and (not out or not out[-1].strip() or out[-1].rstrip().endswith(tuple(OPENERS))):
                continue
            if not blank and out and not out[-1].strip() and ln.lstrip().startswith(tuple(CLOSERS)):
                out.pop()
            gap = False
        out.append(ln)
    return "".join(out)


def apply_mask(text: str, masked: List[Tuple[int, int]], docstrings: List[Tuple[int, int, int, bool]]) -> Tuple[str, List[int]]:
    chars = list(text)
    for s, e in masked:
        for k in range(s, e):
            if chars[k] not in "\r\n":
                chars[k] = SENTINEL
    lines = split_lines("".join(chars))
    result: List[Optional[str]] = []
    touched: List[int] = []
    doc_first = {d[0]: d for d in docstrings}
    doc_inside = set()
    for d in docstrings:
        doc_inside.update(range(d[0], d[1] + 1))
    for no, ln in enumerate(lines, 1):
        if no in doc_first:
            d = doc_first[no]
            if d[3]:
                result.append(" " * d[2] + "pass\n")
            else:
                result.append(None)
            touched.append(no)
            continue
        if no in doc_inside:
            result.append(None)
            touched.append(no)
            continue
        if SENTINEL not in ln:
            result.append(ln)
            continue
        touched.append(no)
        eol = ln[len(ln.rstrip("\r\n")):]
        body = ln[:len(ln) - len(eol)]
        first = body.index(SENTINEL)
        before = body[:first]
        if not before.strip() and not body.replace(SENTINEL, "").strip():
            result.append(None)
            continue
        pieces: List[str] = []
        k = 0
        while k < len(body):
            if body[k] == SENTINEL:
                m = k
                while m < len(body) and body[m] == SENTINEL:
                    m += 1
                left = pieces[-1][-1:] if pieces and pieces[-1] else ""
                right = body[m:m + 1]
                if left and right and not left.isspace() and not right.isspace():
                    pieces.append(" ")
                elif not "".join(pieces).strip() or left.isspace():
                    while m < len(body) and body[m] in " \t":
                        m += 1
                k = m
            else:
                m = k
                while m < len(body) and body[m] != SENTINEL:
                    m += 1
                pieces.append(body[k:m])
                k = m
        new = "".join(pieces)
        if body.rstrip().endswith(SENTINEL) or not body[body.rindex(SENTINEL) + 1:].strip():
            new = new.rstrip()
        result.append(new + eol)
    return tidy(result, True), touched


def strip_text(lang: str, path: str, text: str, strip_safety: bool) -> Result:
    docstrings: List[Tuple[int, int, int, bool]] = []
    if lang == "rust":
        spans = rust_spans(text)
    elif lang == "dart":
        spans = dart_spans(text)
        spans.sort()
    elif lang == "shell":
        spans = shell_spans(text)
    else:
        spans, docstrings = python_spans(text, path)
    line_of = lambda p: text.count("\n", 0, p) + 1
    keep = [keep_comment(lang, text, s, e, k, line_of(s)) for s, e, k in spans]
    if lang == "rust" and not strip_safety:
        extend_safety(text, spans, keep)
    elif lang == "rust":
        keep = [k and not re.match(r"//\s*SAFETY\b", text[s:e]) for k, (s, e, _) in zip(keep, spans)]
    if lang == "python":
        keep = [
            k or line_of(s) == 1 and text[s:e].startswith("#!") or bool(KEEP_PYTHON.match(text[s:e][1:].strip()))
            for k, (s, e, _) in zip(keep, spans)
        ]
    masked = [(s, e) for (s, e, _), k in zip(spans, keep) if not k]
    removed = [
        Removed(path, line_of(s), kind, text[s:e])
        for (s, e, kind), k in zip(spans, keep)
        if not k
    ]
    for first, last, col, _ in docstrings:
        lines = split_lines(text, False)
        removed.append(Removed(path, first, "docstring", "\n".join(lines[first - 1:last])))
    if not masked and not docstrings:
        return Result(text, [], sum(keep))
    new, _ = apply_mask(text, masked, docstrings)
    if lang == "python":
        try:
            ast.parse(new)
        except SyntaxError as err:
            raise SystemExit(f"{path}: stripping broke the syntax: {err}")
    return Result(new, removed, sum(keep))


def comment_lines(lang: str, text: str, path: str) -> int:
    if lang == "rust":
        spans = rust_spans(text)
        docs: List[Tuple[int, int, int, bool]] = []
    elif lang == "dart":
        spans = dart_spans(text)
        docs = []
    elif lang == "shell":
        spans = shell_spans(text)
        docs = []
    else:
        spans, docs = python_spans(text, path)
    covered = set()
    for s, e, _ in spans:
        covered.update(range(text.count("\n", 0, s) + 1, text.count("\n", 0, max(s, e - 1)) + 2))
    for first, last, _, _ in docs:
        covered.update(range(first, last + 1))
    return len(covered)


def git_files(root: Path) -> List[str]:
    out = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True, check=True).stdout
    return out.splitlines()


def language_of(path: str) -> Optional[str]:
    if SKIP_NAMES.search(path) or any(d in path if d.startswith("/") else path.startswith(d) for d in SKIP_DIRS):
        return None
    for lang, prefixes, exts in SCOPE:
        if path.endswith(exts) and any(path.startswith(p) for p in prefixes):
            if lang == "shell" and "/" in path and not path.startswith("tools/"):
                continue
            return lang
    return None


def read_source(path: Path) -> Optional[str]:
    try:
        return path.read_bytes().decode("utf-8")
    except UnicodeDecodeError:
        return None


def main(argv: Optional[Iterable[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=DESCRIPTION)
    ap.add_argument("--root", default=".", help="the repository root (default: the current folder)")
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if any file has a comment to remove")
    ap.add_argument("--count", action="store_true", help="change nothing; print comment lines per language")
    ap.add_argument("--report", help="write every removed comment to this JSON lines file")
    ap.add_argument("--strip-safety", action="store_true", help="also remove // SAFETY: comments, kept by default")
    ap.add_argument("paths", nargs="*", help="only these files (repository-relative)")
    args = ap.parse_args(list(argv) if argv is not None else None)
    root = Path(args.root).resolve()
    files = args.paths or git_files(root)
    before: Counter = Counter()
    after: Counter = Counter()
    totals: Counter = Counter()
    changed: List[str] = []
    report: List[Removed] = []
    for rel in files:
        lang = language_of(rel)
        if lang is None:
            continue
        text = read_source(root / rel)
        if text is None:
            continue
        head = "\n".join(split_lines(text, False)[:5])
        if GENERATED_HEADER.search(head):
            continue
        before[lang] += comment_lines(lang, text, rel)
        totals[lang] += 1
        if args.count:
            continue
        result = strip_text(lang, rel, text, args.strip_safety)
        report.extend(result.removed)
        after[lang] += comment_lines(lang, result.text, rel)
        if result.text != text:
            changed.append(rel)
            if not args.check:
                (root / rel).write_bytes(result.text.encode("utf-8"))
    if args.report:
        with open(args.report, "w", encoding="utf-8") as fh:
            for r in report:
                fh.write(json.dumps({"path": r.path, "line": r.line, "kind": r.kind, "text": r.text}, ensure_ascii=False) + "\n")
    for lang in sorted(totals):
        if args.count:
            print(f"{lang}: {totals[lang]} files, {before[lang]} lines with comments")
        else:
            print(f"{lang}: {totals[lang]} files, {before[lang]} -> {after[lang]} lines with comments")
    if args.check:
        for rel in changed:
            print(f"would change {rel}")
        return 1 if changed else 0
    if not args.count:
        print(f"changed {len(changed)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
