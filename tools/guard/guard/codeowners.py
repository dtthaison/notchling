"""`.github/CODEOWNERS`, generated from zones.json: the maintainer owns everything, the zone has
no owner. CODEOWNERS uses the last matching line, so exclusions come back after the zone lines."""

from __future__ import annotations

from typing import List

from guard.zones import Zones

OWNER = "@dtthaison"
HEADER = """# Generated by `python3 -m guard codeowners --write` from tools/guard/zones.json. Don't edit by hand.
# The maintainer owns everything; the auto-merge zone has no owner.
# Tests, fixtures and phone tests have no owner either: a new one is fine, while an edit to an
# existing one trips maintainer-gate (ZONE and WEAK-TEST-EDIT).
"""


def _pattern(glob: str) -> str:
    if glob.endswith("/**"):
        return "/" + glob[:-2]
    return "/" + glob


def render(zones: Zones) -> str:
    lines: List[str] = [HEADER.rstrip("\n"), "", f"* {OWNER}", "", "# Auto-merge zone"]
    back: List[str] = []
    for g in zones.auto:
        if g.startswith("!"):
            back.append(f"{_pattern(g[1:])} {OWNER}")
        else:
            lines.append(_pattern(g))
    lines += ["", "# New files only"] + [_pattern(g) for g in zones.new_files_only]
    lines += ["", "# Taken back out of the zone"] + back
    return "\n".join(lines) + "\n"
