from __future__ import annotations

from typing import Dict, List, Optional, Tuple

import check
import ftl
from check import Tree
from ftl import Lit, Message, Select, Term

HEADER = "// @generated by tools/locale/gen.py from locales/; do not edit."
RUST_KEYWORDS = {
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct",
    "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "try", "typeof", "unsized", "virtual", "yield", "gen",
}
NO_RAW = {"self", "super", "crate"}
CATS = ("zero", "one", "two", "few", "many", "other")


def ident(word: str) -> str:
    if word in NO_RAW:
        return word + "_"
    if word in RUST_KEYWORDS:
        return "r#" + word
    return word


def literal(text: str) -> str:
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ftl.hidden(ch):
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def tag_ident(tag: str) -> str:
    return tag.upper().replace("-", "_")


def merge(parts: List) -> List:
    out: List = []
    for part in parts:
        if isinstance(part, Lit) and out and isinstance(out[-1], Lit):
            out[-1] = Lit(out[-1].text + part.text)
        else:
            out.append(part)
    return out


class Used:
    def __init__(self) -> None:
        self.cat = False
        self.part = False


def parts_expr(pattern, order: List[str], types: Dict[str, str], terms: Dict[str, str], used: Used) -> str:
    flat: List = []
    for part in pattern:
        if isinstance(part, Term):
            flat.append(Lit(terms[part.name]))
        else:
            flat.append(part)
    items: List[str] = []
    for part in merge(flat):
        if isinstance(part, Lit):
            items.append(f"Part::Lit({literal(part.text)})")
        else:
            idx = order.index(part.name)
            is_num = isinstance(part, ftl.Num) or types.get(part.name) == "num"
            items.append(f"Part::{'Int' if is_num else 'Str'}({idx})")
    used.part = True
    return "&[" + ", ".join(items) + "]"


def body_expr(msg: Message, order: List[str], types: Dict[str, str], terms: Dict[str, str], used: Used) -> str:
    if isinstance(msg.value, Select):
        used.cat = True
        variants = sorted(msg.value.variants, key=lambda v: CATS.index(v.category))
        arms = ", ".join(
            f"(Cat::{v.category.capitalize()}, {parts_expr(v.pattern, order, types, terms, used)})" for v in variants
        )
        return f"Body::Plural({order.index(msg.value.var)}, &[{arms}])"
    flat: List = []
    for part in msg.value:
        flat.append(Lit(terms[part.name]) if isinstance(part, Term) else part)
    flat = merge(flat)
    if all(isinstance(p, Lit) for p in flat):
        return f"Body::Plain({literal(''.join(p.text for p in flat))})"
    return f"Body::Parts({parts_expr(msg.value, order, types, terms, used)})"


def render(tree: Tree) -> str:
    cfg = tree.config
    en_all = check.english(tree)
    en_lang = tree.langs[cfg.source]
    terms = en_lang.files["shared.ftl"].terms if "shared.ftl" in en_lang.files else {}
    en_rust: Dict[str, Tuple[str, Message]] = {
        key: pair for key, pair in en_all.items() if "rust" in check.targets(pair[0])
    }
    keys = sorted(en_rust)
    ids = {key: i for i, key in enumerate(keys)}
    if len(keys) > 65535:
        raise ValueError("more than 65535 messages")
    used = Used()
    orders = {key: check.var_order(en_rust[key][1]) for key in keys}
    types = {key: check.var_types_of(en_rust[key][1]) for key in keys}

    modules: Dict[str, List[str]] = {}
    module_use: Dict[str, set] = {}
    for key in keys:
        first, _, rest = key.partition("-")
        name = "_".join(rest.split("-"))
        fn = ident(name)
        const = name.upper()
        order = orders[key]
        mod_use = module_use.setdefault(first, set())
        mod_use.add("Text")
        items = modules.setdefault(first, [])
        msg = en_rust[key][1]
        is_plain = not order and not isinstance(msg.value, Select)
        if is_plain and not any(not isinstance(p, (Lit, Term)) for p in msg.value):
            items.append(f"    pub const {const}: Text = Text({ids[key]});")
            items.append(f"    pub fn {fn}() -> &'static str {{\n        {const}.get()\n    }}")
        else:
            params = []
            args = []
            for var in order:
                pname = ident(var)
                if types[key].get(var) == "num":
                    params.append(f"{pname}: impl Into<Num>")
                    args.append(f"Arg::Num({pname}.into())")
                    mod_use.add("Num")
                else:
                    params.append(f"{pname}: &str")
                    args.append(f"Arg::Str({pname})")
            mod_use.add("Arg")
            items.append(
                f"    pub fn {fn}({', '.join(params)}) -> String {{\n"
                f"        crate::format(Text({ids[key]}), &[{', '.join(args)}])\n    }}"
            )

    en_bodies = [body_expr(en_rust[k][1], orders[k], types[k], terms, used) for k in keys]
    tables: List[Tuple[str, str, List[Optional[str]]]] = []
    for tag in cfg.ship:
        if tag == cfg.source or tag not in tree.langs:
            continue
        found: Dict[str, Message] = {}
        for rel, res in sorted(tree.langs[tag].files.items()):
            if "rust" not in check.targets(rel):
                continue
            for msg in res.messages:
                if msg.key in en_rust and en_rust[msg.key][0] == rel:
                    found[msg.key] = msg
        rows: List[Optional[str]] = []
        for key in keys:
            if key in found:
                rows.append(body_expr(found[key], orders[key], types[key], terms, used))
            else:
                rows.append(None)
        tables.append((tag, tag_ident(tag), rows))

    out: List[str] = [HEADER]
    imports = ["Body"]
    if used.cat:
        imports.append("Cat")
    if used.part:
        imports.append("Part")
    imports.append("Table")
    out.append(f"use crate::format::{{{', '.join(imports)}}};")
    out.append("use crate::Text;")
    out.append("")
    for first in sorted(modules):
        names = ", ".join(sorted(module_use[first], key=lambda n: (n != "Arg", n != "Num", n)))
        out.append(f"pub mod {first} {{")
        out.append(f"    use crate::{names};" if "," not in names else f"    use crate::{{{names}}};")
        out.append("")
        out.append("\n\n".join(modules[first]))
        out.append("}")
        out.append("")
    out.append(f"pub(crate) const COUNT: usize = {len(keys)};")
    out.append("")
    out.append("pub(crate) static KEYS: [(&str, Text); COUNT] = [")
    for key in keys:
        out.append(f'    ("{key}", Text({ids[key]})),')
    out.append("];")
    out.append("")
    out.append("pub(crate) static EN: [Body; COUNT] = [")
    for expr in en_bodies:
        out.append(f"    {expr},")
    out.append("];")
    out.append("")
    for tag, name, rows in tables:
        out.append(f"pub(crate) static {name}: [Option<Body>; COUNT] = [")
        for expr in rows:
            out.append("    None," if expr is None else f"    Some({expr}),")
        out.append("];")
        out.append("")
    out.append(f"pub(crate) static TABLES: [(&str, Table); {1 + len(tables)}] = [")
    out.append(f'    ("{cfg.source}", Table::Full(&EN)),')
    for tag, name, _ in tables:
        out.append(f'    ("{tag}", Table::Part(&{name})),')
    out.append("];")
    return "\n".join(out) + "\n"
