import release

CARGO_TOML = """[workspace]
members = ["crates/*"]

[workspace.package]
version = "0.1.0"
edition = "2021"

[workspace.dependencies]
serde = "1"
"""

CARGO_LOCK = """# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "gpui"
version = "0.2.2"
dependencies = [
 "notchling-core",
]

[[package]]
name = "notchling-app"
version = "0.1.0"
dependencies = [
 "notchling-core",
 "serde",
]

[[package]]
name = "notchling-core"
version = "0.1.0"

[[package]]
name = "serde"
version = "0.1.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"
"""

CHANGELOG = """# Changelog

## [Unreleased]

### Added

- Already there.

## [0.1.0] - 2026-01-01

### Added

- First.

[Unreleased]: https://github.com/dtthaison/notchling/compare/v0.1.0...HEAD
[0.1.0]: https://github.com/dtthaison/notchling/releases/tag/v0.1.0
"""

FAKE_GH = """#!/bin/sh
printf '%s\\n' "$@" > "$GH_RECORD"
echo https://github.com/example/pull/1
"""


def frag(kind, text):
    return f"---\nkind: {kind}\n---\n{text}\n"


def sh(cwd, *argv):
    env = dict(os.environ, GIT_AUTHOR_NAME="T", GIT_AUTHOR_EMAIL="t@example.com",
               GIT_COMMITTER_NAME="T", GIT_COMMITTER_EMAIL="t@example.com")
    r = subprocess.run(list(argv), cwd=str(cwd), capture_output=True, text=True, env=env)
    if r.returncode != 0:
        raise AssertionError(f"{argv}: {r.stderr}")
    return r.stdout


class ReleaseToolTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        root = Path(self.tmp.name)
        self.origin = root / "origin.git"
        self.repo = root / "repo"
        sh(root, "git", "init", "-q", "--bare", "-b", "main", str(self.origin))
        sh(root, "git", "clone", "-q", str(self.origin), str(self.repo))
        sh(self.repo, "git", "switch", "-q", "-c", "main")
        sh(self.repo, "git", "config", "user.name", "T")
        sh(self.repo, "git", "config", "user.email", "t@example.com")
        (self.repo / "Cargo.toml").write_text(CARGO_TOML)
        (self.repo / "Cargo.lock").write_text(CARGO_LOCK)
        (self.repo / "CHANGELOG.md").write_text(CHANGELOG)
        (self.repo / "changes").mkdir()
        (self.repo / "changes" / "README.md").write_text("About fragments.\n")
        (self.repo / "changes" / "a-feature.md").write_text(frag("feature", "A new thing."))
        (self.repo / "changes" / "b-fix.md").write_text(frag("fix", "A fixed thing."))
        sh(self.repo, "git", "add", ".")
        sh(self.repo, "git", "commit", "-q", "-m", "start")
        sh(self.repo, "git", "push", "-q", "-u", "origin", "main")

    def run_tool(self, *argv, env=None):
        out, err = io.StringIO(), io.StringIO()
        with mock.patch.dict(os.environ, env or {}), redirect_stdout(out), redirect_stderr(err):
            code = release.main([*argv, "--repo", str(self.repo)])
        return code, out.getvalue(), err.getvalue()

    def state(self):
        return (sh(self.repo, "git", "rev-parse", "HEAD"),
                sh(self.repo, "git", "branch", "--show-current"),
                sh(self.repo, "git", "branch", "--list"),
                sh(self.repo, "git", "tag", "--list"),
                sh(self.repo, "git", "status", "--porcelain"))

    def remote_branches(self):
        return sh(self.origin, "git", "branch", "--list")

    def test_dry_run_writes_nothing_and_prints_the_section(self):
        before = self.state()
        code, out, err = self.run_tool("2.0.0", "--dry-run", "--date", "2026-11-17")
        self.assertEqual(code, 0, err)
        self.assertEqual(self.state(), before)
        self.assertIn("0.1.0 -> 2.0.0", out)
        self.assertIn("2 package(s)", out)
        self.assertIn("notchling-app, notchling-core", out)
        self.assertIn("a-feature.md", out)
        self.assertIn("b-fix.md", out)
        self.assertIn("## [2.0.0] - 2026-11-17", out)
        self.assertIn("- A new thing.", out)
        self.assertIn("- A fixed thing.", out)
        self.assertEqual((self.repo / "Cargo.toml").read_text(), CARGO_TOML)
        self.assertTrue((self.repo / "changes" / "a-feature.md").exists())

    def test_dry_run_tolerates_a_dirty_tree(self):
        (self.repo / "scratch.txt").write_text("x")
        code, _, err = self.run_tool("2.0.0", "--dry-run")
        self.assertEqual(code, 0, err)
        self.assertEqual((self.repo / "Cargo.toml").read_text(), CARGO_TOML)

    def test_real_run_makes_the_branch_and_one_commit(self):
        main_head = sh(self.repo, "git", "rev-parse", "HEAD").strip()
        code, out, err = self.run_tool("2.0.0", "--date", "2026-11-17")
        self.assertEqual(code, 0, err)
        self.assertEqual(sh(self.repo, "git", "branch", "--show-current").strip(), "release/2.0.0")
        self.assertEqual(sh(self.repo, "git", "rev-list", f"{main_head}..HEAD", "--count").strip(), "1")
        self.assertEqual(sh(self.repo, "git", "log", "-1", "--format=%s").strip(), "Notchling 2.0.0")
        self.assertEqual(sh(self.repo, "git", "status", "--porcelain"), "")
        changed = sorted(sh(self.repo, "git", "diff", "--name-status", f"{main_head}..HEAD").split("\n")[:-1])
        self.assertEqual(changed, sorted([
            "M\tCHANGELOG.md", "M\tCargo.lock", "M\tCargo.toml",
            "D\tchanges/a-feature.md", "D\tchanges/b-fix.md"]))
        self.assertEqual((self.repo / "Cargo.toml").read_text(), CARGO_TOML.replace('version = "0.1.0"', 'version = "2.0.0"'))
        lock = (self.repo / "Cargo.lock").read_text()
        expected = CARGO_LOCK.replace('name = "notchling-app"\nversion = "0.1.0"', 'name = "notchling-app"\nversion = "2.0.0"')
        expected = expected.replace('name = "notchling-core"\nversion = "0.1.0"', 'name = "notchling-core"\nversion = "2.0.0"')
        self.assertEqual(lock, expected)
        self.assertIn('name = "gpui"\nversion = "0.2.2"', lock)
        self.assertIn('name = "serde"\nversion = "0.1.0"', lock)
        log = (self.repo / "CHANGELOG.md").read_text()
        self.assertIn("## [2.0.0] - 2026-11-17", log)
        self.assertIn("- Already there.", log)
        self.assertIn("- A new thing.", log)
        self.assertIn("[Unreleased]: https://github.com/dtthaison/notchling/compare/v2.0.0...HEAD", log)
        self.assertTrue((self.repo / "changes" / "README.md").exists())
        self.assertFalse((self.repo / "changes" / "a-feature.md").exists())
        self.assertIn("git push -u origin release/2.0.0", out)

    def test_no_push_without_the_flag(self):
        code, _, err = self.run_tool("2.0.0")
        self.assertEqual(code, 0, err)
        self.assertNotIn("release/2.0.0", self.remote_branches())

    def test_push(self):
        code, _, err = self.run_tool("2.0.0", "--push")
        self.assertEqual(code, 0, err)
        self.assertIn("release/2.0.0", self.remote_branches())

    def test_open_pr_pushes_and_calls_gh(self):
        bin_dir = Path(self.tmp.name) / "bin"
        bin_dir.mkdir()
        gh = bin_dir / "gh"
        gh.write_text(FAKE_GH)
        gh.chmod(gh.stat().st_mode | stat.S_IXUSR)
        record = Path(self.tmp.name) / "gh-args"
        code, out, err = self.run_tool(
            "2.0.0", "--open-pr",
            env={"PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}", "GH_RECORD": str(record)})
        self.assertEqual(code, 0, err)
        self.assertIn("release/2.0.0", self.remote_branches())
        args = record.read_text().split("\n")[:-1]
        self.assertEqual(args[:8], ["pr", "create", "--base", "main", "--head", "release/2.0.0",
                                    "--title", "Notchling 2.0.0"])
        self.assertEqual(args[8], "--body")
        self.assertIn("v2.0.0", args[9])

    def test_gh_is_not_called_without_open_pr(self):
        bin_dir = Path(self.tmp.name) / "bin"
        bin_dir.mkdir()
        gh = bin_dir / "gh"
        gh.write_text(FAKE_GH)
        gh.chmod(gh.stat().st_mode | stat.S_IXUSR)
        record = Path(self.tmp.name) / "gh-args"
        code, _, err = self.run_tool(
            "2.0.0", "--push",
            env={"PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}", "GH_RECORD": str(record)})
        self.assertEqual(code, 0, err)
        self.assertFalse(record.exists())

    def refused(self, *argv, reason):
        before = self.state()
        code, out, err = self.run_tool(*argv)
        self.assertEqual(code, 1, out + err)
        self.assertIn(reason, err)
        self.assertEqual(self.state(), before)
        self.assertEqual((self.repo / "Cargo.toml").read_text(), CARGO_TOML)
        self.assertTrue((self.repo / "changes" / "a-feature.md").exists())
        self.assertNotIn("release/", self.remote_branches())

    def test_refuses_a_bad_version(self):
        self.refused("2.0", reason="not X.Y.Z")
        self.refused("v2.0.0", reason="not X.Y.Z")

    def test_refuses_a_version_that_is_not_newer(self):
        self.refused("0.1.0", reason="isn't newer than 0.1.0")
        self.refused("0.0.9", reason="isn't newer than 0.1.0")

    def test_refuses_an_existing_tag(self):
        sh(self.repo, "git", "tag", "v2.0.0")
        self.refused("2.0.0", reason="already tagged")

    def test_refuses_a_tag_found_by_the_fetch(self):
        other = Path(self.tmp.name) / "other"
        sh(self.tmp.name, "git", "clone", "-q", str(self.origin), str(other))
        sh(other, "git", "tag", "v2.0.0")
        sh(other, "git", "push", "-q", "origin", "v2.0.0")
        code, _, err = self.run_tool("2.0.0")
        self.assertEqual(code, 1)
        self.assertIn("already tagged", err)
        self.assertEqual(sh(self.repo, "git", "branch", "--list"), "* main\n")
        self.assertEqual((self.repo / "Cargo.toml").read_text(), CARGO_TOML)

    def test_refuses_a_dirty_tree(self):
        (self.repo / "scratch.txt").write_text("x")
        before = self.state()
        code, _, err = self.run_tool("2.0.0")
        self.assertEqual(code, 1)
        self.assertIn("Commit or stash", err)
        self.assertEqual(self.state(), before)

    def test_refuses_an_existing_branch(self):
        sh(self.repo, "git", "branch", "release/2.0.0")
        self.refused("2.0.0", reason="already exists")

    def test_a_failure_after_the_switch_restores_the_repo(self):
        (self.repo / "changes" / "bad.md").write_text("no front matter\n")
        sh(self.repo, "git", "add", ".")
        sh(self.repo, "git", "commit", "-q", "-m", "bad fragment")
        sh(self.repo, "git", "push", "-q", "origin", "main")
        before = self.state()
        code, _, err = self.run_tool("2.0.0")
        self.assertEqual(code, 1)
        self.assertIn("bad.md", err)
        self.assertEqual(self.state(), before)


class LockTest(unittest.TestCase):
    def test_only_path_packages_at_the_old_version_change(self):
        text, names = release.bump_cargo_lock(CARGO_LOCK, "0.1.0", "1.0.0")
        self.assertEqual(names, ["notchling-app", "notchling-core"])
        self.assertEqual(text.count('version = "1.0.0"'), 2)
        self.assertIn('name = "serde"\nversion = "0.1.0"\nsource', text)

    def test_other_bytes_stay(self):
        crlf = CARGO_LOCK.replace("\n", "\r\n")
        text, _ = release.bump_cargo_lock(crlf, "0.1.0", "1.0.0")
        self.assertEqual(text.replace('"1.0.0"', '"0.1.0"').replace("1.0.0", "0.1.0"), crlf)

    def test_workspace_version_reads_only_its_section(self):
        self.assertEqual(release.workspace_version('[package]\nversion = "9.9.9"\n' + CARGO_TOML), "0.1.0")


if __name__ == "__main__":
    unittest.main()
