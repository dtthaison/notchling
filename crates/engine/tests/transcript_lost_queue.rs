    r#"{"type":"queue-operation","operation":"dequeue","timestamp":"2026-11-13T13:20:30.000Z"}"#;
const TAKES_LOST: &str = r#"{"type":"user","message":{"role":"user","content":"the context under the reply box should have no background"},"timestamp":"2026-11-13T13:20:31.000Z"}"#;
const DIRECT: &str = r#"{"type":"user","message":{"role":"user","content":"why?"},"timestamp":"2026-11-13T13:15:52.300Z"}"#;
const DIRECT_BLOCKS: &str = r#"{"type":"user","message":{"role":"user","content":[{"type":"text","text":"why?"}]},"timestamp":"2026-11-13T13:15:52.300Z"}"#;
const DIRECT_BASH: &str = r#"{"type":"user","message":{"role":"user","content":"<bash-input>git branch</bash-input>"},"timestamp":"2026-11-13T13:15:52.300Z"}"#;
